  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read zones') THEN
    CREATE POLICY "Public read zones" ON zones FOR SELECT USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read observations') THEN
    CREATE POLICY "Public read observations" ON observations FOR SELECT USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read forecasts') THEN
    CREATE POLICY "Public read forecasts" ON forecasts FOR SELECT USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read model_runs') THEN
    CREATE POLICY "Public read model_runs" ON model_runs FOR SELECT USING (true);
  END IF;
END $$;

