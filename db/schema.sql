ALTER TABLE forecasts ENABLE ROW LEVEL SECURITY;
ALTER TABLE alerts ENABLE ROW LEVEL SECURITY;
ALTER TABLE briefings ENABLE ROW LEVEL SECURITY;
ALTER TABLE incident_actions ENABLE ROW LEVEL SECURITY;
ALTER TABLE model_runs ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS alerts_user_zone_day_created_idx
  ON alerts (user_id, zone_id, days_ahead, created_at DESC);
CREATE INDEX IF NOT EXISTS briefings_user_created_idx
  ON briefings (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS incident_actions_user_created_idx
  ON incident_actions (user_id, created_at DESC);

