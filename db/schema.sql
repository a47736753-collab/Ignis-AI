-- IGNIS AI: PostgreSQL schema for persistent storage.
-- Run this once on your database (Supabase SQL Editor, psql, Neon console, etc.).

CREATE TABLE IF NOT EXISTS zones (
  id          TEXT PRIMARY KEY,            -- e.g. 'D5'
  name        TEXT,
  geojson     JSONB,                       -- zone polygon
  created_at  TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS observations (
  id          BIGSERIAL PRIMARY KEY,
  zone_id     TEXT REFERENCES zones(id),
  source      TEXT NOT NULL,               -- 'open-meteo' | 'sentinel-2' | 'nasa-firms'
  kind        TEXT NOT NULL,               -- 'observed' | 'forecast'
  observed_at TIMESTAMPTZ NOT NULL,
  values      JSONB NOT NULL               -- e.g. {"temp_c":34,"humidity":31,"wind_kmh":11,"ndvi":0.46}
);

CREATE TABLE IF NOT EXISTS forecasts (
  id          BIGSERIAL PRIMARY KEY,
  zone_id     TEXT REFERENCES zones(id),
  run_at      TIMESTAMPTZ DEFAULT now(),
  target_date DATE NOT NULL,
  score       NUMERIC(5,2) NOT NULL        -- 0 to 100, from your risk model
);

CREATE TABLE IF NOT EXISTS alerts (
  id           BIGSERIAL PRIMARY KEY,
  user_id      TEXT,
  zone_id      TEXT NOT NULL,
  days_ahead   INT  NOT NULL CHECK (days_ahead BETWEEN 1 AND 7),
  score        NUMERIC(5,2) NOT NULL CHECK (score BETWEEN 0 AND 100),
  acknowledged BOOLEAN DEFAULT false,
  acknowledged_at TIMESTAMPTZ,
  acknowledged_by TEXT,
  created_at   TIMESTAMPTZ DEFAULT now()
);

-- Ensure columns exist if table was already created
ALTER TABLE alerts ADD COLUMN IF NOT EXISTS acknowledged BOOLEAN DEFAULT false;
ALTER TABLE alerts ADD COLUMN IF NOT EXISTS acknowledged_at TIMESTAMPTZ;
ALTER TABLE alerts ADD COLUMN IF NOT EXISTS acknowledged_by TEXT;
ALTER TABLE alerts ADD COLUMN IF NOT EXISTS user_id TEXT;

-- Operational briefings generated by Groq AI and approved by officers
CREATE TABLE IF NOT EXISTS briefings (
  id           BIGSERIAL PRIMARY KEY,
  user_id      TEXT,
  user_email   TEXT,
  title        TEXT,
  threat_level TEXT,
  summary      TEXT,
  content      TEXT NOT NULL,
  actions      JSONB,
  created_at   TIMESTAMPTZ DEFAULT now()
);

-- Incident command actions: dispatches, checklist confirmations, simulated drills
CREATE TABLE IF NOT EXISTS incident_actions (
  id           BIGSERIAL PRIMARY KEY,
  user_id      TEXT,
  action_type  TEXT NOT NULL,               -- 'dispatch' | 'checklist' | 'drill' | 'advisory'
  zone_id      TEXT,
  payload      JSONB,
  performed_by TEXT,
  created_at   TIMESTAMPTZ DEFAULT now()
);
ALTER TABLE incident_actions ADD COLUMN IF NOT EXISTS user_id TEXT;

CREATE TABLE IF NOT EXISTS model_runs (
  id          BIGSERIAL PRIMARY KEY,
  model_name  TEXT,
  version     TEXT,
  metrics     JSONB,                       -- e.g. {"roc_auc":0.0,"precision":0.0,"recall":0.0}
  created_at  TIMESTAMPTZ DEFAULT now()
);

